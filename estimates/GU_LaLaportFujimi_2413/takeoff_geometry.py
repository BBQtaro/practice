def polygon_area(pts):
    s = 0.0
    for (x1, y1), (x2, y2) in zip(pts, pts[1:] + pts[:1]):
        s += x1 * y2 - x2 * y1
    return abs(s) / 2 / 1e6  # ㎡


def wall_length(wid, pts):
    if wid in SEGMENT_WALLS:
        return sum(hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts[::2], pts[1::2])) / 1000
    return sum(hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts, pts[1:])) / 1000


def wall_rows():
    rows = []
    for wid, name, pts, h, base, fin, faces, color, ref in WALLS:
        L = wall_length(wid, pts)
        rows.append(dict(id=wid, name=name, length=round(L, 2), height=h, base=base, finish=fin,
                         faces=faces, area=round(L * h / 1000, 1), color=color, ref=ref, pts=pts))
    return rows


def zone_rows():
    return [dict(id=z, name=n, finish=f, color=c, pts=p, area=round(polygon_area(p), 1),
                 official=OFFICIAL_AREA.get(n)) for z, n, f, c, p in ZONES]


